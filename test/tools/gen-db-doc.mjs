#!/usr/bin/env node
/**
 * pnpm gen:db-doc — writes src/utils/buildDocs/designDb.ts (the Design tab "נתונים (DB)") from
 * artifacts/tables/*.json and artifacts/views/*.json, plus the title, intro and table → component map in
 * memories/files/DESIGN_DB.md. Run it after every table or view change; never edit designDb.ts by hand.
 * Lives under test/ because the platform keeps only src/** and test/** (scripts/ does not survive publishing).
 * The relations (arrows of the ER view) stay hand-kept in src/utils/buildDocs/dbRelations.ts.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(root, 'src/utils/buildDocs/designDb.ts');
const MD = join(root, 'memories/files/DESIGN_DB.md');

function readJsonDir(dir) {
  const abs = join(root, dir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(abs, f), 'utf8')));
}

/** Title (H1), intro bullets (## מבוא…) and the component groups (## שיוך לרכיבים) from DESIGN_DB.md. */
function readSpec() {
  const lines = readFileSync(MD, 'utf8').split(/\r?\n/);
  const title = (lines.find((l) => l.startsWith('# ')) ?? '# נתונים (DB)').slice(2).trim();
  const intro = [];
  const groups = [];
  let section = '';
  for (const line of lines) {
    if (line.startsWith('## ')) {
      section = line.slice(3).trim();
      continue;
    }
    if (section.startsWith('מבוא') && line.startsWith('- ')) intro.push(line.slice(2).trim());
    if (section.startsWith('שיוך לרכיבים')) {
      const m = line.match(/^- \*\*(.+?):\*\*\s*(.*)$/);
      if (!m || m[1].trim() === 'Views') continue;
      const names = m[2]
        .split(',')
        // A note after the name ("AgingNotes (יוצאת אחרי המיגרציה)") is for the reader, not part of the name.
        .map((s) => s.replace(/\s*\([^)]*\)\s*$/, '').trim())
        .filter((s) => /^[A-Za-z][A-Za-z0-9]*$/.test(s));
      groups.push({ title: m[1].trim(), mirror: m[1].includes('מראות'), names });
    }
  }
  return { title, intro, groups };
}

function tableDoc(t, mirror) {
  const doc = {
    kind: 'table',
    name: t.name,
    description: t.description ?? '',
    technicalDescription: t.technicalDescription ?? '',
    mirror,
  };
  doc.uniqueKey = Array.isArray(t.uniqueKey) ? t.uniqueKey : [];
  doc.columns = (t.columns ?? []).map((c) => {
    const col = { name: c.name, type: c.type };
    if (Array.isArray(c.enum) && c.enum.length) col.enum = c.enum;
    col.description = c.description ?? '';
    return col;
  });
  return doc;
}

function viewDoc(v) {
  const q = v.query ?? {};
  const select = (q.select ?? []).map((s) => ({
    name: s.as ?? s.column,
    type: s.expression ? `ביטוי: ${s.expression}` : s.function ? `${s.function}(${s.column})` : s.column,
    description: '',
  }));
  const calculated = (v.calculatedColumns ?? []).map((c) => ({
    name: c.name,
    type: `${c.type} (מחושב)`,
    description: c.description ?? '',
  }));
  return {
    kind: 'view',
    name: v.name,
    description: v.description ?? '',
    technicalDescription: v.technicalDescription ?? '',
    mirror: false,
    baseTable: q.from?.table ?? '',
    joins: (q.join ?? []).map((j) => j.table),
    columns: [...select, ...calculated],
  };
}

const spec = readSpec();
const tables = readJsonDir('artifacts/tables');
const views = readJsonDir('artifacts/views');
const byName = new Map(tables.map((t) => [t.name, t]));
const placed = new Set();
const groups = spec.groups.map((g) => {
  const list = g.names
    .filter((n) => byName.has(n) && !placed.has(n))
    .map((n) => {
      placed.add(n);
      return tableDoc(byName.get(n), g.mirror);
    });
  return { title: g.title, mirror: g.mirror, tables: list };
});
const rest = tables.filter((t) => !placed.has(t.name)).map((t) => tableDoc(t, false));
if (rest.length) groups.push({ title: 'אחר', mirror: false, tables: rest });

// Each view sits beside its base table's group (alphabetical among the views); an unknown base goes to אחר.
for (const v of [...views].sort((a, b) => a.name.localeCompare(b.name))) {
  const doc = viewDoc(v);
  let group = groups.find((g) => g.tables.some((t) => t.kind === 'table' && t.name === doc.baseTable));
  if (!group) {
    group = groups.find((g) => g.title === 'אחר');
    if (!group) groups.push((group = { title: 'אחר', mirror: false, tables: [] }));
  }
  group.tables.push(doc);
}

const out = {
  title: spec.title,
  intro: spec.intro,
  groups: groups.filter((g) => g.tables.length > 0),
  tableCount: tables.length,
  viewCount: views.length,
};

const header = `/**
 * GENERATED by test/tools/gen-db-doc.mjs — do not edit by hand. Re-run \`pnpm gen:db-doc\` after every table change.
 * Tables and views from artifacts/tables/*.json and artifacts/views/*.json; the intro and the component of each table
 * from memories/files/DESIGN_DB.md. Rendered by /collections/design, tab "נתונים (DB)" (?doc=db).
 */

export interface DbColumn {
  name: string;
  /** The column type; for a view, where the value comes from. */
  type: string;
  /** Allowed values, when the column is an enum. */
  enum?: string[];
  description: string;
}

export interface DbTable {
  kind: 'table' | 'view';
  name: string;
  description: string;
  technicalDescription: string;
  /** A Priority mirror: read-only in the app. */
  mirror: boolean;
  uniqueKey?: string[];
  /** A view's base table, and the tables it joins. */
  baseTable?: string;
  joins?: string[];
  columns: DbColumn[];
}

export interface DbGroup {
  title: string;
  /** The group of Priority mirrors. */
  mirror: boolean;
  tables: DbTable[];
}

export const DESIGN_DB: { title: string; intro: string[]; groups: DbGroup[]; tableCount: number; viewCount: number } = `;

writeFileSync(OUT, `${header}${JSON.stringify(out, null, 2)};\n`);
console.log(`designDb.ts: ${out.tableCount} tables, ${out.viewCount} views, ${out.groups.length} groups`);